# ===================== 核心处理逻辑 =====================
import re

# 1. 先把所有剧集按 集数 整理成字典（方便按序号操作）
episodes = {}
for url, info in data.items():
    title = info[1]
    # 提取数字：第xx集
    match = re.search(r'第(\d+)集', title)
    if match:
        num = int(match.group(1))
        episodes[num] = info

# 2. 按你的规则替换链接
# 规则：
# 第1集 → 空
# 第2集 = 第1集原链接
# 第3集 = 第2集原链接
# ...
# 第69集 = 第68集原链接
# 第70集 → 不变

# 先保存原始链接
original_links = {n: episodes[n][0] for n in episodes}

# 执行替换
for n in episodes:
    if n == 1:
        episodes[n][0] = ""  # 第1集置空
    elif 2 <= n <= 69:
        episodes[n][0] = original_links[n-1]  # 用上一集链接覆盖当前集
    # 70集不处理，保持原样

# 3. 把修改后的数据写回原字典
for url, info in data.items():
    title = info[1]
    match = re.search(r'第(\d+)集', title)
    if match:
        num = int(match.group(1))
        info[0] = episodes[num][0]

